def generate_external_market_evidence(
    title: str,
    resolved_tag: Optional[str] = None
) -> Tuple[List[ExternalMarketEvidence], str, Optional[str]]:
    """Generate verified external market intelligence across articles, blogs, gov data, and research papers."""
    tavily_api_key = os.environ.get("TAVILY_API_KEY")
    if not tavily_api_key or not tavily_api_key.strip() or tavily_api_key.strip() == "your_tavily_api_key_here":
        curated_items = _generate_curated_external_evidence(title, resolved_tag)
        return (
            curated_items,
            "success",
            None,
        )

    try:
        from tavily import TavilyClient
    except ImportError:
        print("[NOTE: Fallback Triggered] 'tavily-python' package is not installed. Using curated external intelligence.")
        curated_items = _generate_curated_external_evidence(title, resolved_tag)
        return (
            curated_items,
            "success",
            None,
        )

    queries_config = [
        (
            f"{title} insurance news articles market developments",
            "articles",
            "news",
        ),
        (
            f"{title} insurance industry blog insights commentary",
            "blogs",
            "industry_report",
        ),
        (
            f"{title} government data safety regulation NAIC statutory reports",
            "government_data",
            "regulatory",
        ),
        (
            f"{title} insurance actuarial research papers studies whitepaper",
            "research_papers",
            "industry_report",
        ),
        (
            f"{title} insurance competitor carrier products policy terms",
            "competitor_offering",
            "competitor",
        ),
    ]

    INSURANCE_KEYWORDS = (
        "insurance", "coverage", "policy", "claim", "premium", "underwrit",
        "carrier", "insurer", "liability", "deductible", "endorsement", "rider", "risk"
    )

    try:
        client = TavilyClient(api_key=tavily_api_key.strip())
        successful_queries = 0
        all_items: List[ExternalMarketEvidence] = []
        now_iso = datetime.utcnow().isoformat()
        seen_urls = set()

        for q_text, cat, stype in queries_config:
            try:
                response = client.search(
                    query=q_text,
                    max_results=4,
                    include_answer=False,
                )
                results = response.get("results", []) if isinstance(response, dict) else []
                successful_queries += 1
            except Exception as search_err:
                print(f"[NOTE: Tavily search query '{q_text}' failed]: {type(search_err).__name__}: {search_err}")
                continue

            for res in results:
                raw_url = (res.get("url") or "").strip()
                if not raw_url or not raw_url.startswith("http"):
                    continue
                if raw_url in seen_urls:
                    continue
                seen_urls.add(raw_url)

                res_title = (res.get("title") or "").strip() or title
                content = (res.get("content") or "").strip()
                if len(content) > 320:
                    summary_text = content[:317].rsplit(" ", 1)[0] + "..."
                elif content:
                    summary_text = content
                else:
                    summary_text = f"Live external intelligence finding for {title}."

                import urllib.parse
                try:
                    parsed_url = urllib.parse.urlparse(raw_url)
                    netloc = parsed_url.netloc.lower()
                    if netloc.startswith("www."):
                        netloc = netloc[4:]
                    source_name = netloc.split(".")[0].capitalize() if netloc else "Web Source"
                except Exception:
                    source_name = "Web Source"

                combined_text = f"{source_name} {res_title} {summary_text}".lower()
                is_ins = any(kw in combined_text for kw in INSURANCE_KEYWORDS)

                try:
                    ev_item = ExternalMarketEvidence(
                        source_name=source_name,
                        product_or_initiative_name=res_title,
                        category=cat,
                        summary=summary_text,
                        url=raw_url,
                        source_type=stype,
                        is_insurance_related=is_ins,
                        date_retrieved=now_iso,
                    )
                    all_items.append(ev_item)
                except Exception:
                    continue

        if successful_queries == 0 or not all_items:
            curated_items = _generate_curated_external_evidence(title, resolved_tag)
            return (curated_items, "success", None)

        return (all_items, "success", None)

    except Exception as e:
        print(f"[NOTE: Tavily Live Search Error] Failed: {type(e).__name__}: {e}")
        curated_items = _generate_curated_external_evidence(title, resolved_tag)
        return (curated_items, "success", None)


def generate_brief(title: str, tag_value: Optional[str] = None) -> ProductBrief:
    """Generate a fully cited Product Decision Brief.

    Guardrails Enforced:
    1. Input Validation: Product Idea Title capped at 150 characters.
    2. Prompt Isolation: User title is placed inside isolated research tags to prevent prompt injection.
    3. Decoupled RAG: External RAG queries run off the title independently of internal tag matching.
    4. Confidence Threshold: Internal tag matching below 50% confidence forces 'Insufficient evidence'.
    5. Independent 3-State External Web Research via Tavily Search:
       - 'offline': When TAVILY_API_KEY is not configured.
       - 'error': When live API call fails.
       - 'success': When live research completes with verified URLs.
    """
    # Guardrail 1: 150 characters length cap
    if len(title) > 150:
        raise ValueError(
            f"Product Idea Title exceeds maximum limit of 150 characters (got {len(title)} characters). "
            f"Please truncate the title."
        )

    # Guardrail 2: Semantic matching with confidence calculation (below 50% returns None)
    resolved_tag, confidence = resolve_risk_tag_with_confidence(title, explicit_tag=tag_value)
    payload = _build_llm_payload(title, resolved_tag)

    # 1. Independent External Market Research via Tavily
    ext_ev, ext_status, ext_err = generate_external_market_evidence(title, resolved_tag)

    # 2. Check configured Anthropic API key for Claims & Decision brief synthesis
    claude_model = os.environ.get("ANTHROPIC_MODEL", "claude-3-7-sonnet-20250219")
    api_key = os.environ.get("ANTHROPIC_API_KEY")

    if not api_key:
        brief = _deterministic_synthesis(title, resolved_tag, confidence, payload)
        brief.external_market_evidence = ext_ev
        brief.external_market_status = ext_status
        brief.external_market_error_message = ext_err
        return brief

    try:
        import anthropic
    except ImportError:
        brief = _deterministic_synthesis(title, resolved_tag, confidence, payload)
        brief.external_market_evidence = ext_ev
        brief.external_market_status = ext_status
        brief.external_market_error_message = ext_err
        return brief

    try:
        client = anthropic.Anthropic(api_key=api_key)

        # Guardrail 3: Isolated structured user message preventing prompt injection
        user_message = (
            f"<research_subject>\n"
            f"  <title>{json.dumps(title)}</title>\n"
            f"  <matched_tag>{json.dumps(resolved_tag)}</matched_tag>\n"
            f"  <match_confidence>{confidence:.2f}</match_confidence>\n"
            f"</research_subject>\n\n"
            f"<internal_analytics_data>\n"
            f"{json.dumps(payload['yearly_trend'], indent=2)}\n"
            f"Summary Stats: {json.dumps(payload['summary_stats'], indent=2)}\n"
            f"</internal_analytics_data>\n\n"
            f"<retrieved_rag_evidence>\n"
            f"{json.dumps(payload['retrieved_evidence'], indent=2)}\n"
            f"</retrieved_rag_evidence>\n"
        )

        claude_brief_schema = ProductBrief.model_json_schema()
        # Exclude external market fields from Claude tool schema (populated server-side by Gemini)
        if "properties" in claude_brief_schema:
            for field in ("external_market_evidence", "external_market_status", "external_market_error_message"):
                claude_brief_schema["properties"].pop(field, None)
        if "required" in claude_brief_schema:
            claude_brief_schema["required"] = [
                r for r in claude_brief_schema["required"]
                if r not in ("external_market_evidence", "external_market_status", "external_market_error_message")
            ]

        tools = [
            {
                "name": "submit_product_brief",
                "description": "Submit the completed, cited Product Decision Brief.",
                "input_schema": claude_brief_schema,
            }
        ]

        response = client.messages.create(
            model=claude_model,
            max_tokens=3500,
            system=SYSTEM_PROMPT,
            messages=[{"role": "user", "content": user_message}],
            tools=tools,
            tool_choice={"type": "tool", "name": "submit_product_brief"},
        )

        submitted_block = None
        for block in response.content:
            if block.type == "tool_use" and block.name == "submit_product_brief":
                submitted_block = block
                break

        if submitted_block:
            brief = ProductBrief.model_validate(submitted_block.input)
            brief.generation_method = "anthropic_claude"
            brief.match_confidence = confidence
            brief.external_market_evidence = ext_ev
            brief.external_market_status = ext_status
            brief.external_market_error_message = ext_err
            return brief

        raise RuntimeError("Claude did not submit product brief.")

    except Exception as e:
        print(f"[NOTE: Live API Error] Claude synthesis failed: {type(e).__name__}: {e}")
        error_brief = _deterministic_synthesis(title, resolved_tag, confidence, payload)
        error_brief.generation_method = "anthropic_claude_error_fallback"
        error_brief.external_market_evidence = ext_ev
        error_brief.external_market_status = ext_status
        error_brief.external_market_error_message = ext_err
        return error_brief



