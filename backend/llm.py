def resolve_risk_tag_with_confidence(
    title: str,
    explicit_tag: Optional[str] = None
) -> Tuple[Optional[str], float]:
    """Resolve internal risk tag and calculate a match confidence score (0.0 to 1.0).

    Guardrail Rules:
    - Explicit user selection -> 1.0 (100% confidence).
    - Exact tag name in title -> 0.85 - 0.95.
    - Strong keyword match (e.g. 'battery', 'theft', 'flood') -> 0.60 - 0.80.
    - Below 0.50 (50%) confidence threshold -> Force return (None, score) so
      internal claims analysis forces 'Insufficient evidence'.
    """
    if explicit_tag and explicit_tag.strip():
        clean_tag = explicit_tag.strip().lower()
        if not clean_tag.startswith("(optional)") and clean_tag not in ("none", "optional", "auto", "unmatched", ""):
            return clean_tag, 1.0

    title_clean = title.strip().lower()
    title_words = set(title_clean.replace("-", " ").replace("_", " ").split())

    best_tag: Optional[str] = None
    best_score: float = 0.0

    for tag, keywords in TAG_SEMANTIC_MAP.items():
        tag_normalized = tag.replace("_", " ")
        # 1. Exact tag name or normalized tag in title
        if tag in title_clean or tag_normalized in title_clean:
            score = 0.92
            if score > best_score:
                best_score = score
                best_tag = tag

        # 2. Keyword matching
        for kw in keywords:
            kw_lower = kw.lower()
            if kw_lower in title_clean:
                if len(kw_lower.split()) > 1:
                    kw_score = 0.82  # multi-word phrase match
                elif kw_lower in title_words:
                    kw_score = 0.72  # exact word token match
                elif len(kw_lower) >= 5:
                    kw_score = 0.55  # substring match
                else:
                    continue         # short keywords ('ev', 'cell') only count as whole words
                if kw_score > best_score:
                    best_score = kw_score
                    best_tag = tag

    # Confidence Threshold Guardrail: below 50% forces Unmatched (None)
    if best_score < 0.50 or not best_tag:
        return None, round(best_score, 2)

    return best_tag, round(best_score, 2)


